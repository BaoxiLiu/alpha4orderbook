"""Factor-pack matrix report (M4)."""

from __future__ import annotations

from pathlib import Path
from typing import Any

import pandas as pd

from .markdown import _df_markdown


def write_pack_report(
    path: str | Path,
    *,
    meta: dict[str, Any],
    mean_by_symbol: pd.DataFrame,
    pivot: pd.DataFrame,
    calendar_split: pd.DataFrame,
    failures: list[dict[str, Any]],
    load_log: list[dict[str, Any]],
    layering_mean: pd.DataFrame | None = None,
    layering_note: str = "",
) -> Path:
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)

    lines: list[str] = []
    lines.append("# Factor pack eval")
    lines.append("")
    lines.append("## Run meta")
    lines.append("")
    for k in (
        "symbols",
        "start_date",
        "end_date",
        "train_dates",
        "test_dates",
        "factor_names",
        "factor_specs",
        "dt_seconds",
        "top_k",
        "n_detail_rows",
        "n_layering_rows",
        "n_quantiles",
        "layering_method",
        "n_failures",
        "elapsed_seconds",
        "panels_root",
        "built_at_utc",
    ):
        if k in meta:
            lines.append(f"- **{k}**: `{meta[k]}`")
    lines.append("")
    lines.append(
        "- Companion HTML charts: `report.html` (Plotly CDN)."
    )
    lines.append("")

    lines.append("## Rank IC matrix (mean across days) — factor × horizon × symbol")
    lines.append("")
    # Compact table from mean_by_symbol
    show = mean_by_symbol.copy()
    show["rank_ic"] = show["rank_ic"].map(lambda x: float(x) if pd.notna(x) else float("nan"))
    lines.append(_df_markdown(show, index=False))
    lines.append("")

    lines.append("### Pivot (rows=spec/factor/horizon, cols=symbol)")
    lines.append("")
    piv = pivot.reset_index()
    lines.append(_df_markdown(piv, index=False))
    lines.append("")

    lines.append("## Calendar-day time split")
    lines.append("")
    lines.append(
        f"> Train = first {meta.get('train_days')} calendar days "
        f"`{meta.get('train_dates')}`; "
        f"test = last {meta.get('test_days')} days `{meta.get('test_dates')}`. "
        "IC values are means of per-day Rank ICs (not pooled ticks)."
    )
    lines.append("")
    lines.append(_df_markdown(calendar_split, index=False))
    lines.append("")

    # Coverage of built panels
    ok = sum(1 for x in load_log if x.get("status") == "ok")
    miss = sum(1 for x in load_log if x.get("status") != "ok")
    lines.append("## Panel load coverage")
    lines.append("")
    lines.append(f"- **loaded ok**: `{ok}`")
    lines.append(f"- **missing / unusable**: `{miss}`")
    lines.append("")
    if miss:
        lines.append("| symbol | date | status |")
        lines.append("| --- | --- | --- |")
        for x in load_log:
            if x.get("status") != "ok":
                lines.append(
                    f"| {x.get('symbol')} | {x.get('date')} | {x.get('status')} |"
                )
        lines.append("")

    if failures:
        lines.append("## Failures")
        lines.append("")
        lines.append(_df_markdown(pd.DataFrame(failures), index=False))
        lines.append("")

    if layering_mean is not None and not layering_mean.empty:
        lines.append("## Quantile layering (分层收益)")
        lines.append("")
        if layering_note:
            lines.append(f"> {layering_note}")
            lines.append("")
        ls = layering_mean[layering_mean["quantile"].astype(str) == "LS"].copy()
        lines.append("### Long-short Q_high − Q_low (equal-day mean)")
        lines.append("")
        lines.append(_df_markdown(ls, index=False))
        lines.append("")
        lines.append("### Full quantile means")
        lines.append("")
        lines.append(_df_markdown(layering_mean, index=False))
        lines.append("")

    lines.append("## Notes")
    lines.append("")
    lines.append("- Built on precomputed L1 day panels; no LOB tick replay per factor.")
    lines.append("- Single-week / 3-symbol slice — expand universe in later M4 runs.")
    lines.append("- Rank IC ≠ tradable edge.")
    lines.append(
        "- **分层** = factor-value TS quantiles within day; depth `L3`/`L5` = book levels."
    )
    lines.append("")
    lines.append("---")
    lines.append("Generated by `python -m a4ob.cli run-eval-pack`.")

    path.write_text("\n".join(lines), encoding="utf-8")
    return path
