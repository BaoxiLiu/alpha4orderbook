"""Markdown report writers."""

from __future__ import annotations

from pathlib import Path
from typing import Any

import pandas as pd


def _df_markdown(df: pd.DataFrame, *, index: bool = True) -> str:
    """Minimal markdown table (no tabulate dependency)."""
    work = df.copy()
    if index:
        work = work.reset_index()
    cols = [str(c) for c in work.columns]
    lines = [
        "| " + " | ".join(cols) + " |",
        "| " + " | ".join("---" for _ in cols) + " |",
    ]
    for row in work.itertuples(index=False):
        cells = []
        for v in row:
            if isinstance(v, float):
                cells.append("nan" if v != v else f"{v:.6g}")
            else:
                cells.append(str(v))
        lines.append("| " + " | ".join(cells) + " |")
    return "\n".join(lines)


def write_smoke_report(
    path: str | Path,
    *,
    meta: dict[str, Any],
    stats: dict[str, Any],
    ic_table: pd.DataFrame,
    panel_head: pd.DataFrame,
) -> Path:
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)

    lines: list[str] = []
    lines.append("# Smoke report — L0 rebuild → L1 panel → baseline IC")
    lines.append("")
    lines.append("## Run meta")
    lines.append("")
    for k, v in meta.items():
        lines.append(f"- **{k}**: `{v}`")
    lines.append("")
    lines.append("## Rebuild stats")
    lines.append("")
    for k, v in stats.items():
        lines.append(f"- **{k}**: `{v}`")
    lines.append("")
    lines.append("## Rank IC (imbalance vs mid forward returns)")
    lines.append("")
    ic_cols = [c for c in ic_table.columns if not c.endswith("__n")]
    n_cols = [c for c in ic_table.columns if c.endswith("__n")]
    lines.append(_df_markdown(ic_table[ic_cols], index=True))
    lines.append("")
    if n_cols:
        lines.append("### Observation counts")
        lines.append("")
        lines.append(_df_markdown(ic_table[n_cols], index=True))
        lines.append("")
    lines.append("## Panel head")
    lines.append("")
    show = [
        c
        for c in panel_head.columns
        if c
        in {
            "ts_ms",
            "symbol",
            "mid",
            "spread",
            "imb_1",
            "imb_5",
            "best_bid",
            "best_ask",
        }
        or c.startswith("ret_fwd_")
    ]
    lines.append(_df_markdown(panel_head[show].head(8), index=False))
    lines.append("")
    lines.append("---")
    lines.append("Generated by `python -m a4ob.cli smoke`.")
    path.write_text("\n".join(lines), encoding="utf-8")
    return path
