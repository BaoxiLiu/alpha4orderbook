"""Fuller Factor Spec evaluation report (M3)."""

from __future__ import annotations

from pathlib import Path
from typing import Any

import pandas as pd

from ..factors.spec import FactorSpec
from .markdown import _df_markdown


def write_eval_report(
    path: str | Path,
    *,
    spec: FactorSpec,
    meta: dict[str, Any],
    suite: dict[str, Any],
) -> Path:
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)

    lines: list[str] = []
    lines.append(f"# Factor eval — `{spec.name}` v{spec.version}")
    lines.append("")
    if spec.description:
        lines.append(spec.description.strip())
        lines.append("")

    lines.append("## Run meta")
    lines.append("")
    for k, v in meta.items():
        if k == "apply":
            continue
        lines.append(f"- **{k}**: `{v}`")
    lines.append(f"- **frequency**: `{spec.frequency}`")
    lines.append(f"- **outputs**: `{spec.output_cols}`")
    lines.append(f"- **metrics**: `{spec.metrics}`")
    lines.append("")

    apply = meta.get("apply") or {}
    if apply.get("steps"):
        lines.append("## Spec steps applied")
        lines.append("")
        for s in apply["steps"]:
            lines.append(f"- `{s['id']}` op=`{s['op']}` → {s['outputs']}")
        lines.append("")
    if apply.get("external_joined"):
        lines.append("### External asof joins")
        lines.append("")
        for e in apply["external_joined"]:
            lines.append(f"- `{e['name']}` ← `{e['path']}`")
        lines.append("")

    if "rank_ic" in suite:
        ic: pd.DataFrame = suite["rank_ic"]
        ic_cols = [c for c in ic.columns if not c.endswith("__n")]
        n_cols = [c for c in ic.columns if c.endswith("__n")]
        lines.append("## Rank IC × horizons")
        lines.append("")
        lines.append(_df_markdown(ic[ic_cols], index=True))
        lines.append("")
        if n_cols:
            lines.append("### Pairwise observation counts")
            lines.append("")
            lines.append(_df_markdown(ic[n_cols], index=True))
            lines.append("")

    if "ic_decay" in suite:
        lines.append(
            f"## IC decay (`{suite.get('primary_factor', spec.primary_factor)}`)"
        )
        lines.append("")
        lines.append(_df_markdown(suite["ic_decay"], index=False))
        lines.append("")

    if "coverage" in suite:
        lines.append("## Coverage")
        lines.append("")
        cov = suite["coverage"]
        # compact: one row per factor (mean pairwise coverage)
        summary = (
            cov.groupby("factor", as_index=False)
            .agg(
                factor_coverage=("factor_coverage", "first"),
                mean_pairwise_coverage=("pairwise_coverage", "mean"),
                min_pairwise_n=("n_pairwise", "min"),
                max_pairwise_n=("n_pairwise", "max"),
            )
        )
        lines.append(_df_markdown(summary, index=False))
        lines.append("")

    if "time_split" in suite:
        lines.append("## Time split (stub)")
        lines.append("")
        note = suite.get("time_split_note", "")
        if note:
            lines.append(f"> {note}")
            lines.append("")
        lines.append(_df_markdown(suite["time_split"], index=False))
        lines.append("")

    lines.append("## Notes")
    lines.append("")
    lines.append(
        "- Labels are mid-to-mid forward returns on the panel clock (no fees/latency)."
    )
    lines.append("- Rank IC ≠ tradable edge; L3 realism is out of scope for this report.")
    lines.append("- Multi-day / cross-symbol folds belong to M4+.")
    lines.append("")
    lines.append("---")
    lines.append("Generated by `python -m a4ob.cli run-eval`.")

    path.write_text("\n".join(lines), encoding="utf-8")
    return path
